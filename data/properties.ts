export function getFeaturedProperties(purpose?: "sale" | "rent"): Property[] {
  return PROPERTIES.filter((p) => {
    if (purpose && p.purpose !== purpose) return false;
    return p.featured;
  });
}

export function getPropertyBySlug(slug: string): Property | undefined {
  return PROPERTIES.find((p) => p.slug === slug);
}

export function getRelatedProperties(current: Property, limit = 3): Property[] {
  return PROPERTIES.filter(
    (p) =>
      p.id !== current.id &&
      (p.purpose === current.purpose ||
        p.location.neighborhood === current.location.neighborhood)
  ).slice(0, limit);
}
