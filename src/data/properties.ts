// Helper Selectors
export const saleProperties = PROPERTIES.filter((p) => p.listingType === 'sale');
export const rentProperties = PROPERTIES.filter((p) => p.listingType === 'rent');

export function getPropertyById(id: string): Property | undefined {
  return PROPERTIES.find((p) => p.id === id);
}

export function getPropertyBySlug(slug: string): Property | undefined {
  return PROPERTIES.find((p) => p.slug === slug);
}

export function getFeaturedProperties(listingType?: 'sale' | 'rent'): Property[] {
  return PROPERTIES.filter((p) => {
    const matchesType = listingType ? p.listingType === listingType : true;
    return matchesType && p.featured;
  });
}
